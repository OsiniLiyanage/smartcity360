-- Additive, rerunnable schema. Routing history is separate from work status.
CREATE TABLE IF NOT EXISTS complaint (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    city_id BIGINT NOT NULL REFERENCES city(id),
    zone_id BIGINT,
    resident_name VARCHAR(100) NOT NULL CHECK (length(trim(resident_name)) > 0),
    subject VARCHAR(160) NOT NULL CHECK (length(trim(subject)) > 0),
    description VARCHAR(2000) NOT NULL CHECK (length(trim(description)) > 0),
    severity VARCHAR(16) NOT NULL CHECK (severity IN ('LOW','MEDIUM','HIGH')),
    assigned_to VARCHAR(24) CHECK (assigned_to IN ('LOCAL_STAFF','SUPERVISOR','CITY_MANAGER')),
    status VARCHAR(24) NOT NULL CHECK (status IN ('UNASSIGNED','ASSIGNED','IN_PROGRESS','RESOLVED')),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    FOREIGN KEY (city_id, zone_id) REFERENCES zone(city_id, id),
    CHECK ((status = 'UNASSIGNED' AND assigned_to IS NULL)
        OR (status <> 'UNASSIGNED' AND assigned_to IS NOT NULL))
);
CREATE TABLE IF NOT EXISTS complaint_event (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    complaint_id BIGINT NOT NULL REFERENCES complaint(id),
    event_type VARCHAR(32) NOT NULL,
    actor VARCHAR(40) NOT NULL,
    message VARCHAR(1200) NOT NULL,
    occurred_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX IF NOT EXISTS complaint_city_updated_idx ON complaint(city_id, updated_at DESC, id DESC);
CREATE INDEX IF NOT EXISTS complaint_event_order_idx ON complaint_event(complaint_id, id);
GRANT SELECT, INSERT, UPDATE ON complaint TO smartcity360_app;
GRANT SELECT, INSERT ON complaint_event TO smartcity360_app;
GRANT USAGE, SELECT ON SEQUENCE complaint_id_seq, complaint_event_id_seq TO smartcity360_app;
