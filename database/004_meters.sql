-- Meter credentials are stored only as hashes; payload encryption keys stay outside the database.
CREATE TABLE IF NOT EXISTS meter (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    city_id BIGINT NOT NULL REFERENCES city(id),
    zone_id BIGINT NOT NULL,
    name VARCHAR(100) NOT NULL CHECK (length(trim(name)) > 0),
    credential_hash VARCHAR(64) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    UNIQUE (city_id, zone_id),
    UNIQUE (city_id, id),
    FOREIGN KEY (city_id, zone_id) REFERENCES zone(city_id, id)
);
CREATE TABLE IF NOT EXISTS meter_reading (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    city_id BIGINT NOT NULL REFERENCES city(id),
    meter_id BIGINT NOT NULL,
    usage_kwh NUMERIC(12,3) NOT NULL CHECK (usage_kwh >= 0),
    authenticated BOOLEAN NOT NULL,
    compressed BOOLEAN NOT NULL,
    encrypted BOOLEAN NOT NULL,
    original_bytes INTEGER NOT NULL CHECK (original_bytes > 0),
    encoded_bytes INTEGER NOT NULL CHECK (encoded_bytes > 0),
    original_hash VARCHAR(64) NOT NULL,
    payload TEXT NOT NULL,
    received_at TIMESTAMP WITH TIME ZONE NOT NULL,
    FOREIGN KEY (city_id, meter_id) REFERENCES meter(city_id, id)
);
CREATE INDEX IF NOT EXISTS meter_reading_history_idx ON meter_reading(city_id, meter_id, id DESC);
GRANT SELECT, INSERT, UPDATE ON meter TO smartcity360_app;
GRANT SELECT, INSERT ON meter_reading TO smartcity360_app;
GRANT USAGE, SELECT ON SEQUENCE meter_id_seq, meter_reading_id_seq TO smartcity360_app;
