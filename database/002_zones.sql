-- Additive migration: preserves all existing city records.
CREATE TABLE IF NOT EXISTS zone (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    city_id BIGINT NOT NULL REFERENCES city(id),
    parent_id BIGINT,
    name VARCHAR(100) NOT NULL CHECK (length(trim(name)) > 0),
    zone_type VARCHAR(16) NOT NULL CHECK (zone_type IN ('DISTRICT','STREET','BUILDING')),
    usage_kwh NUMERIC(12,3),
    power_on BOOLEAN,
    UNIQUE (city_id, id),
    FOREIGN KEY (city_id, parent_id) REFERENCES zone(city_id, id),
    CHECK (parent_id IS NULL OR parent_id <> id),
    CHECK ((zone_type = 'DISTRICT' AND parent_id IS NULL)
        OR (zone_type <> 'DISTRICT' AND parent_id IS NOT NULL)),
    CHECK ((zone_type = 'BUILDING' AND usage_kwh IS NOT NULL AND usage_kwh >= 0 AND power_on IS NOT NULL)
        OR (zone_type <> 'BUILDING' AND usage_kwh IS NULL AND power_on IS NULL))
);
CREATE INDEX IF NOT EXISTS zone_city_parent_idx ON zone(city_id, parent_id);
GRANT SELECT, INSERT, UPDATE, DELETE ON zone TO smartcity360_app;
GRANT USAGE, SELECT ON SEQUENCE zone_id_seq TO smartcity360_app;
