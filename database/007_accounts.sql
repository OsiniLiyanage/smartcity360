CREATE TABLE IF NOT EXISTS app_user (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(254) NOT NULL UNIQUE CHECK (email = lower(email)),
    display_name VARCHAR(100) NOT NULL CHECK (length(trim(display_name)) > 0),
    password_hash VARCHAR(200) NOT NULL,
    role VARCHAR(20) NOT NULL CHECK (role IN ('RESIDENT','LOCAL_STAFF','SUPERVISOR','CITY_MANAGER','SYSTEM_ADMIN')),
    city_id BIGINT REFERENCES city(id),
    enabled BOOLEAN NOT NULL DEFAULT true,
    password_change_required BOOLEAN NOT NULL DEFAULT false,
    security_version BIGINT NOT NULL DEFAULT 0,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK ((role IN ('RESIDENT','SYSTEM_ADMIN') AND city_id IS NULL) OR (role IN ('LOCAL_STAFF','SUPERVISOR','CITY_MANAGER') AND city_id IS NOT NULL))
);
CREATE TABLE IF NOT EXISTS account_event (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_id BIGINT REFERENCES app_user(id),
    target_id BIGINT NOT NULL REFERENCES app_user(id),
    action VARCHAR(40) NOT NULL,
    occurred_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
ALTER TABLE complaint ADD COLUMN IF NOT EXISTS owner_id BIGINT REFERENCES app_user(id);
ALTER TABLE complaint_event ADD COLUMN IF NOT EXISTS actor_user_id BIGINT REFERENCES app_user(id);
ALTER TABLE complaint_event ADD COLUMN IF NOT EXISTS public_message VARCHAR(1200);
