-- Immutable lamp specifications shared by individual streetlight records.
CREATE TABLE IF NOT EXISTS lamp_specification (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    model VARCHAR(100) NOT NULL CHECK (length(trim(model)) > 0),
    rated_watts INTEGER NOT NULL CHECK (rated_watts BETWEEN 1 AND 1000),
    colour VARCHAR(24) NOT NULL CHECK (colour IN ('WARM_WHITE','NEUTRAL_WHITE','COOL_WHITE')),
    UNIQUE (model, rated_watts, colour)
);
INSERT INTO lamp_specification(model, rated_watts, colour) VALUES
    ('CityLED 40',40,'WARM_WHITE'),('CityLED 60',60,'NEUTRAL_WHITE'),('AvenueLED 100',100,'COOL_WHITE')
ON CONFLICT (model,rated_watts,colour) DO NOTHING;
CREATE TABLE IF NOT EXISTS streetlight (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    city_id BIGINT NOT NULL REFERENCES city(id),
    street_id BIGINT NOT NULL,
    specification_id BIGINT NOT NULL REFERENCES lamp_specification(id),
    label VARCHAR(60) NOT NULL CHECK (length(trim(label)) > 0),
    location VARCHAR(150) NOT NULL CHECK (length(trim(location)) > 0),
    power_on BOOLEAN NOT NULL,
    faulty BOOLEAN NOT NULL,
    fault_note VARCHAR(500) NOT NULL DEFAULT '',
    version BIGINT NOT NULL DEFAULT 0,
    UNIQUE (city_id, label),
    FOREIGN KEY (city_id, street_id) REFERENCES zone(city_id, id),
    CHECK ((faulty AND length(trim(fault_note)) > 0) OR (NOT faulty AND fault_note = ''))
);
CREATE INDEX IF NOT EXISTS streetlight_city_id_idx ON streetlight(city_id, id);
GRANT SELECT, INSERT ON lamp_specification TO smartcity360_app;
GRANT SELECT, INSERT, UPDATE ON streetlight TO smartcity360_app;
GRANT USAGE, SELECT ON SEQUENCE lamp_specification_id_seq, streetlight_id_seq TO smartcity360_app;
