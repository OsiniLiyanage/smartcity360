CREATE TABLE IF NOT EXISTS policy (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    city_id BIGINT NOT NULL REFERENCES city(id),
    name VARCHAR(80) NOT NULL CHECK (length(trim(name)) > 0),
    category VARCHAR(12) NOT NULL CHECK (category IN ('NOISE','PARKING','CUSTOM')),
    expression VARCHAR(1000) NOT NULL CHECK (length(trim(expression)) > 0),
    true_meaning VARCHAR(12) NOT NULL CHECK (true_meaning IN ('VIOLATION','PERMITTED')),
    active BOOLEAN NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    UNIQUE(city_id, name), UNIQUE(city_id, id)
);
CREATE TABLE IF NOT EXISTS policy_evaluation (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    city_id BIGINT NOT NULL,
    policy_id BIGINT NOT NULL,
    zone_id BIGINT NOT NULL,
    policy_version BIGINT NOT NULL,
    policy_name VARCHAR(80) NOT NULL,
    category VARCHAR(12) NOT NULL,
    expression VARCHAR(1000) NOT NULL,
    true_meaning VARCHAR(12) NOT NULL CHECK (true_meaning IN ('VIOLATION','PERMITTED')),
    noise NUMERIC(6,3) CHECK (noise BETWEEN 0 AND 200),
    hour INTEGER CHECK (hour BETWEEN 0 AND 23),
    parking_minutes INTEGER CHECK (parking_minutes BETWEEN 0 AND 10080),
    matched BOOLEAN NOT NULL,
    note VARCHAR(500) NOT NULL DEFAULT '',
    evaluated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    FOREIGN KEY (city_id, policy_id) REFERENCES policy(city_id, id),
    FOREIGN KEY (city_id, zone_id) REFERENCES zone(city_id, id)
);
CREATE INDEX IF NOT EXISTS policy_evaluation_history_idx ON policy_evaluation(city_id, policy_id, id DESC);
