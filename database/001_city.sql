-- Initial, additive schema. Re-running preserves existing city records.
CREATE TABLE IF NOT EXISTS city (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL CHECK (length(trim(name)) > 0)
);
GRANT SELECT, INSERT, UPDATE, DELETE ON city TO smartcity360_app;
GRANT USAGE, SELECT ON SEQUENCE city_id_seq TO smartcity360_app;
